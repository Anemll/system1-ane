"""Serve engine for an Unsloth (Clef joint-schema head) decision model on the Core AI backbone.

The merged-LoRA backbone runs on the ANE (the Core AI runtime's prefill, rows kept from the last chunk); the final RMSNorm and
the Clef head run either on the host in PyTorch (default, fp32 on the CPU, about 8 ms) or, with
``CLEF_HEAD_BACKEND=ane``, as a fixed-shape fp16 Core AI package (about 3 ms; see ``clef_ane_head.py``). A build opts in
by shipping ``clef_head/`` (the Unsloth ``adapter_head`` files: ``joint_head.safetensors``, ``joint_head_config.json``,
``unsloth_decision_config.json``) next to its ``manifest.json``. The ANE package (``clef_head_ane.aimodel`` and
``ane_head_config.json``) is generated by ``python coreai/clef_ane_head.py <clef_head dir>``, not stored in Git. Prompts over
304 rows or 8 options fall back to the host head.
"""
from __future__ import annotations

import os
import time
from pathlib import Path

import numpy as np
import torch

from clef_head import ClefHead
from jeff_coreai import rms_last


def has_clef_head(build: Path) -> bool:
    return (Path(build) / "clef_head" / "joint_head.safetensors").is_file()


class ClefEngine:
    def __init__(self, runtime, build: Path, tokenize):
        """tokenize(state, instructions, options) -> {input_ids, question_span, option_keys, option_spans}."""
        self.runtime, self.tokenize = runtime, tokenize
        self.head = ClefHead(Path(build) / "clef_head")
        self.embed = torch.from_numpy(np.asarray(runtime.emb, np.float32))
        h = self.head  # CLEF_HEAD_DTYPE=fp32|fp16|bf16 (default fp32), CLEF_HEAD_DEVICE=cpu|mps (default cpu)
        self.head_desc = f"{str(h.dtype).replace('torch.', '')}/{h.device.type} ({h.weights_file})"
        # CLEF_HEAD_BACKEND=host (default, the PyTorch head above) | ane (fixed-shape fp16 Core AI package, clef_head/ane_head_config.json)
        self.ane_head = None
        if (os.environ.get("CLEF_HEAD_BACKEND") or "host").lower() == "ane":
            from clef_ane_head import AneHeadRunner
            self.ane_head = AneHeadRunner(Path(build) / "clef_head", runtime.loop)
            self.head_desc = f"fp16/ane ({self.ane_head.cfg['file']}; host fallback {self.head_desc})"
        self.backend = f"coreai-ane {runtime.entry} + clef-head(host {self.head_desc})"
        torch.set_num_threads(max(1, min(4, torch.get_num_threads())))

    def logits_for(self, enc: dict) -> tuple[np.ndarray, dict]:
        ids = [int(t) for t in enc["input_ids"]]
        r = self.runtime.prefill(ids, keep_chunks=True)
        rows = r["chunks"][-1]  # (n, hid): last chunk output, before the final RMSNorm
        t0 = time.perf_counter()
        hidden = torch.from_numpy(rms_last(rows, self.runtime.norm, self.runtime.eps))
        if self.ane_head is not None and self.ane_head.fits(hidden.shape[0], len(enc["option_spans"])):
            logits = torch.from_numpy(self.ane_head(hidden.numpy(), ids, self.embed, enc["question_span"], enc["option_spans"]))
        else:  # host head (CLEF_HEAD_DTYPE / CLEF_HEAD_DEVICE); also the ANE backend's fallback for >T rows or >K options
            logits = self.head(hidden, ids, self.embed, enc["question_span"], enc["option_spans"])
        r["head_ms"] = 1e3 * (time.perf_counter() - t0)
        return logits.numpy(), r

    def decide_row(self, state, question: dict) -> dict:
        options = {k: ("" if v is None else v) for k, v in question["criteria"].items()}
        enc = self.tokenize(state, question.get("instructions") or "Choose the best matching option.", options)
        logits, r = self.logits_for(enc)
        probs = torch.softmax(torch.from_numpy(logits) / self.head.t_choice, -1).numpy()
        by_key = dict(zip(enc["option_keys"], probs.tolist()))
        order = list(question["criteria"])
        return {"option_probabilities": [by_key[k] for k in order], "calls_ms": [float(x) for x in r["calls_ms"]],
                "head_ms": float(r["head_ms"]), "call_widths": [int(x) for x in r["call_widths"]],
                "prefix_tokens": 0, "tokens": len(enc["input_ids"])}

    def capture_state(self):
        return self.runtime.capture_state()

    def prefill_info(self) -> dict:
        return {"widths": list(self.runtime.widths), "mode": self.runtime.mode, "head": f"clef (host {self.head_desc})"}
